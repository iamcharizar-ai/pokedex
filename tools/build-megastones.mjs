// Mega Stone pictures: the 24x24 sprites from the PokeFarm wiki (tools/megastones-src, one per stone) blown up 8 times,
// pixel for pixel, into sprites/megastones/<mega form>.png (192x192). Nothing is smoothed: every output pixel is a copy of one
// source pixel, so the colours stay exactly the artist's and the edges stay hard. The browser draws them with `image-rendering: pixelated`.
//
//   node tools/build-megastones.mjs
//
// It also writes src/lib/megastone-art.ts, the list of forms that have a picture; the others keep the drawn orb (Ball.tsx).
import fs from 'node:fs'
import path from 'node:path'
import { PNG } from 'pngjs'
import { SPECIES } from '../core/species.ts'
import { megaStoneName } from '../src/lib/stone-names.ts'

const ROOT = path.resolve(import.meta.dirname, '..')
const SRC = path.join(ROOT, 'tools/megastones-src')
const OUT = path.join(ROOT, 'sprites/megastones')
const SCALE = 8

/** The wiki's file for a Mega form is Mega_Stone_<its stone's name, with _ for spaces>.png. */
const wikiName = (form) => megaStoneName(form).replace(/ /g, '_')

fs.rmSync(OUT, { recursive: true, force: true })
fs.mkdirSync(OUT, { recursive: true })
const made = [], missing = [], used = []
for (const [id, s] of Object.entries(SPECIES)) for (const form of s.m ?? []) {
  const file = path.join(SRC, `Mega_Stone_${wikiName(form)}.png`)
  if (!fs.existsSync(file)) { missing.push(form); continue }
  used.push(path.basename(file))
  const src = PNG.sync.read(fs.readFileSync(file))
  const out = new PNG({ width: src.width * SCALE, height: src.height * SCALE })
  for (let y = 0; y < out.height; y++) for (let x = 0; x < out.width; x++) {
    const from = ((Math.floor(y / SCALE)) * src.width + Math.floor(x / SCALE)) * 4
    src.data.copy(out.data, (y * out.width + x) * 4, from, from + 4)
  }
  fs.writeFileSync(path.join(OUT, `${form}.png`), PNG.sync.write(out))
  made.push(form)
}
fs.writeFileSync(path.join(ROOT, 'src/lib/megastone-art.ts'),
  `// GENERATED by tools/build-megastones.mjs. Do not edit by hand.\n// The Mega forms whose stone has a picture in sprites/megastones; the rest are drawn as an orb.\nexport const MEGASTONE_ART: ReadonlySet<string> = new Set(${JSON.stringify(made)})\n`)
if (process.argv.includes("--prune")) for (const f of fs.readdirSync(SRC)) if (!used.includes(f)) fs.rmSync(path.join(SRC, f))
console.log(`${made.length} stone pictures written; no picture for ${missing.length}: ${missing.join(', ')}`)
