// Copies the motion kit into Life OS (src/ui-kit), the way build-core.mjs copies the game core.
// Life OS keeps its own look (paper, hard borders); what it shares is how things MOVE: the same
// timings, easings and choreography, so a claim or a flourish feels the same in both apps.
//   npm run kit
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const DEST = path.resolve(ROOT, '../lifeos/src/ui-kit')
const FILES = [['src/lib/motion.js', 'motion.js'], ['src/lib/motion.d.ts', 'motion.d.ts']]

if (!fs.existsSync(path.dirname(DEST))) { console.error('Life OS not found next to this repo; nothing copied.'); process.exit(0) }
fs.mkdirSync(DEST, { recursive: true })
for (const [from, to] of FILES) fs.copyFileSync(path.join(ROOT, from), path.join(DEST, to))

// the timings as CSS, read from the tokens file so there is one source
const tokens = fs.readFileSync(path.join(ROOT, 'src/styles/tokens.css'), 'utf8')
const motion = [...tokens.matchAll(/(--(?:t-fade|t-slide|t-pop|t-breathe|ease-out|ease-in-out|ease-in):[^;]+;)/g)].map((m) => `  ${m[1]}`)
fs.writeFileSync(path.join(DEST, 'motion-tokens.css'), `/* Generated by the Pokedex repo's \`npm run kit\` from its styles/tokens.css. Do not edit here. */\n:root {\n${motion.join('\n')}\n}\n`)
fs.writeFileSync(path.join(DEST, 'README.md'), '# ui-kit\n\nCopied from the pokedex repo by `npm run kit` there. Do not edit it here.\n\n`motion.js` is the motion kit measured in the animation study (timings, easings, choreography; no art or sound). `motion-tokens.css` is the same timings as CSS variables.\n')
console.log(`copied ${FILES.length + 2} files to ${DEST}`)
